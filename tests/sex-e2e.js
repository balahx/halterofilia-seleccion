/* Sexo obligatorio: al crear la cuenta y, para cuentas antiguas sin sexo, al entrar a la app. Uso: node tests/sex-e2e.js */
const { chromium } = require('playwright');
const http = require('http'), fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png', '.webmanifest': 'application/manifest+json' };
const srv = http.createServer((q, r) => { let p = decodeURIComponent(q.url.split('?')[0]); if (p === '/') p = '/index.html'; const f = path.join(ROOT, p); if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { r.writeHead(404); r.end(); return; } r.writeHead(200, { 'Content-Type': MIME[path.extname(f)] || 'application/octet-stream' }); r.end(fs.readFileSync(f)); });
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? '  ✓ ' : '  ✗ ') + m); };
(async () => {
  await new Promise(r => srv.listen(0, r)); const URL = 'http://localhost:' + srv.address().port + '/';
  const br = await chromium.launch(), errors = [];
  const ctx = await br.newContext({ viewport: { width: 390, height: 780 }, serviceWorkers: 'block' });
  await ctx.addInitScript({ path: path.join(__dirname, 'fake-remote.js') });
  const page = await ctx.newPage();
  page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error' && !/fonts\.g|net::ERR/.test(m.text())) errors.push(m.text()); });
  await page.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
  await page.goto(URL); await page.waitForSelector('#gForm');
  await page.click('[data-g="mode"][data-v="signup"]');
  ok(await page.locator('#gSex').count() === 1 && (await page.locator('#gSex').inputValue()) === '', 'el formulario de registro pide el sexo, sin valor elegido');
  await page.fill('#gName', 'Ana Rojas'); await page.fill('#gEmail', 'ana@correo.cl'); await page.fill('#gPass', 'clave123'); await page.fill('#gPass2', 'clave123'); await page.check('#gPriv');
  await page.click('#gForm button[type=submit]'); await page.waitForTimeout(300);
  ok(/Indica tu sexo/.test(await page.locator('#gErr').innerText()), 'sin sexo no se crea la cuenta: avisa');
  ok(await page.evaluate(() => !__fake.uid('ana@correo.cl')), 'la cuenta no se creó');
  await page.selectOption('#gSex', 'M'); await page.click('#gForm button[type=submit]');
  await page.waitForFunction(() => /Solicitud enviada/.test(document.querySelector('#gate h1')?.textContent || ''));
  const uid = await page.evaluate(() => __fake.uid('ana@correo.cl'));
  await page.evaluate(u => __fake.admin('members/' + u, { name: 'Ana Rojas', email: 'ana@correo.cl', approvedAt: Date.now() }), uid);
  await page.waitForSelector('#appRoot:not([hidden])');
  ok(await page.locator('#dlg[open]').count() === 0, 'al entrar no se le vuelve a preguntar el sexo');
  ok(await page.evaluate(u => JSON.parse(localStorage.getItem('halterofilia.v1.' + u)).profile.sex, uid) === 'M', 'el sexo elegido al registrarse quedó en su perfil');
  await page.click('#gear'); await page.waitForSelector('#sSex');
  ok(await page.locator('#sSex option').count() === 2, 'en Ajustes se puede cambiar, pero no dejar vacío');
  await page.keyboard.press('Escape'); await page.waitForTimeout(200);

  console.log('Cuenta antigua sin sexo');
  await page.evaluate(u => { const k = 'halterofilia.v1.' + u, o = JSON.parse(localStorage.getItem(k)); o.profile.sex = ''; localStorage.setItem(k, JSON.stringify(o)); }, uid);
  await page.evaluate(u => { const k = 'halterofilia.v1.' + u + '.sync'; localStorage.removeItem(k); }, uid);
  await page.evaluate(u => __fake.admin('users/' + u + '/records/profile', { t: 'profile', d: JSON.stringify({ name: 'Ana Rojas', sex: '' }), u: Date.now() + 5000, at: Date.now() + 5000 }), uid);
  await page.reload(); await page.waitForSelector('#dlg[open]', { timeout: 8000 });
  ok(/Indica tu sexo/.test(await page.locator('#dlg h2').innerText()), 'al entrar se le pide indicar el sexo');
  ok(await page.locator('#dlg [data-act="sheet-close"]').count() === 0, 'la ventana no tiene botón para cerrarla');
  await page.keyboard.press('Escape'); await page.waitForTimeout(300);
  ok(await page.locator('#dlg[open]').count() === 1, 'Escape no la cierra');
  await page.click('#dlg [data-act="set-sex"][data-v="F"]'); await page.waitForTimeout(300);
  ok(await page.locator('#dlg[open]').count() === 0, 'al elegir, se cierra');
  ok(await page.evaluate(u => JSON.parse(localStorage.getItem('halterofilia.v1.' + u)).profile.sex, uid) === 'F', 'el sexo queda guardado');
  console.log(errors.length ? 'Errores: ' + errors.join(' | ') : 'Sin errores de consola ni de página');
  await br.close(); srv.close();
  console.log(fails || errors.length ? 'HAY FALLAS' : 'Todo bien'); process.exit(fails || errors.length ? 1 : 0);
})();
