/* Diseño WL · Selección: portada de ingreso, marca, colores claro/oscuro, menú inferior de atleta y de entrenador,
   pantalla «Más» y sus accesos. Uso: node tests/design-e2e.js  (con SHOTS=carpeta guarda capturas) */
const { chromium } = require('playwright');
const http = require('http'), fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..'), SHOTS = process.env.SHOTS || path.join(__dirname, 'shots');
fs.mkdirSync(SHOTS, { recursive: true });
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png', '.webmanifest': 'application/manifest+json' };
const srv = http.createServer((q, r) => { let p = decodeURIComponent(q.url.split('?')[0]); if (p === '/') p = '/index.html'; const f = path.join(ROOT, p); if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { r.writeHead(404); return r.end('no'); } r.writeHead(200, { 'content-type': MIME[path.extname(f)] || 'application/octet-stream' }); r.end(fs.readFileSync(f)); });
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log((c ? '  ✓ ' : '  ✗ ') + m); };

(async () => {
  await new Promise(r => srv.listen(0, r)); const URL = 'http://localhost:' + srv.address().port + '/';
  const br = await chromium.launch(), errors = [];
  const ctx = await br.newContext({ viewport: { width: +(process.env.VW || 390), height: +(process.env.VH || 780) }, deviceScaleFactor: +(process.env.DSF || 2), serviceWorkers: 'block', colorScheme: 'light' });
  await ctx.addInitScript({ path: path.join(__dirname, 'fake-remote.js') });
  await ctx.addInitScript(() => { window.__viol = []; document.addEventListener('securitypolicyviolation', e => window.__viol.push(e.violatedDirective + ' ' + e.blockedURI)); });
  const page = await ctx.newPage();
  page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error' && !/fonts\.g|net::ERR/.test(m.text())) errors.push(m.text()); });
  await page.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
  const txt = sel => page.locator(sel).first().innerText();
  const shot = n => page.screenshot({ path: path.join(SHOTS, 'wl-' + n + '.png') });
  const navLabels = () => page.locator('#nav button span').allInnerTexts();
  const css = (sel, prop) => page.evaluate(([s, p]) => getComputedStyle(document.querySelector(s))[p], [sel, prop]);
  const logout = async () => { await page.click('#nav [data-tab="mas"]'); await page.click('.mrow[data-act="cl-logout"]'); await page.waitForSelector('#gForm'); await page.waitForTimeout(500); };
  const signup = async (name, email, sex) => { await page.click('[data-g="mode"][data-v="signup"]'); await page.selectOption('#gSex', sex); await page.fill('#gName', name); await page.fill('#gEmail', email); await page.fill('#gPass', 'clave123'); await page.fill('#gPass2', 'clave123'); await page.check('#gPriv'); await page.click('#gForm button[type=submit]'); await page.waitForFunction(() => /Solicitud enviada/.test(document.querySelector('#gate h1')?.textContent || '')); };
  const login = async email => { await page.fill('#gEmail', email); await page.fill('#gPass', 'clave123'); await page.click('#gForm button[type=submit]'); await page.waitForSelector('#appRoot:not([hidden])', { timeout: 8000 }); await page.waitForTimeout(300); };

  console.log('1. Portada de ingreso con la marca WL');
  await page.goto(URL); await page.waitForSelector('#gForm');
  const hero = await txt('#gate .hero');
  ok(/WL/.test(hero) && /SELECCIÓN/.test(hero) && /La fuerza de la disciplina/.test(hero), 'la portada muestra WL, SELECCIÓN y el lema');
  ok(/wl-marca-claro\.svg/.test(await css('#gate .hero .mk', 'backgroundImage')), 'el logo claro del caballito de mar en modo claro');
  ok((await css('body', 'backgroundColor')) === 'rgb(243, 245, 249)', 'fondo claro #F3F5F9');
  ok((await css('#gate .btn, #gate button[type=submit]', 'backgroundColor')) === 'rgb(39, 79, 131)', 'botón en azul de marca #274F83');
  await shot('01-ingreso-claro');
  ok((await page.title()) === 'WL · Selección de Halterofilia', 'título de la página');
  const mf = JSON.parse(fs.readFileSync(path.join(ROOT, 'manifest.webmanifest'), 'utf8'));
  ok(mf.short_name === 'WL Selección' && mf.theme_color === '#274F83' && mf.background_color === '#0E1A2E', 'manifest: nombre y colores de la marca');
  for (const i of mf.icons) ok(fs.existsSync(path.join(ROOT, i.src.split('?')[0])), 'existe ' + i.src);
  await page.emulateMedia({ colorScheme: 'dark' }); await page.waitForTimeout(150);
  ok((await css('body', 'backgroundColor')) === 'rgb(14, 26, 46)' && /wl-marca-oscuro\.svg/.test(await css('#gate .hero .mk', 'backgroundImage')), 'modo oscuro: fondo #0E1A2E y logo dorado claro');
  await shot('02-ingreso-oscuro');
  await page.emulateMedia({ colorScheme: 'light' });

  console.log('2. Entrenador: Equipo · Marcas · Planes · Mi sesión · Más');
  await signup('Cristian Mateluna', 'cristian@correo.cl', 'M');
  const cuid = await page.evaluate(() => __fake.uid('cristian@correo.cl'));
  await page.evaluate(u => __fake.admin('config/team', { coachUid: u }), cuid);
  await page.waitForSelector('#appRoot:not([hidden])');
  ok((await navLabels()).join('|') === 'Equipo|Marcas|Planes|Mi sesión|Más', 'menú del entrenador: ' + (await navLabels()).join(' · '));
  ok((await txt('header.top .brand')).trim() === 'WL' && /wl-marca-claro/.test(await css('header.top .mk', 'backgroundImage')), 'cabecera con el logo y «WL»');
  await page.click('#nav [data-tab="mas"]'); await page.waitForTimeout(200);
  let mas = await txt('#view');
  ok(/Cristian Mateluna/.test(mas) && /Entrenador/.test(mas) && /Descargar respaldo del equipo/.test(mas) && /Solicitudes de acceso/.test(mas), '«Más» del entrenador: perfil, respaldo y solicitudes');
  ok(/Progreso/.test(mas) && /Máximos/.test(mas) && /Plan semanal libre/.test(mas) && /Aviso de privacidad/.test(mas) && /Cerrar sesión/.test(mas), 'y su entrenamiento propio, aviso y cerrar sesión');
  ok((await page.locator('#nav [aria-current="page"]').getAttribute('data-tab')) === 'mas', '«Más» queda marcada');
  await shot('03-mas-entrenador');
  await page.click('.mrow[data-tab="prog"]'); await page.waitForTimeout(200);
  ok(/Progreso/.test(await txt('#view h1')) && (await page.locator('#nav [aria-current="page"]').getAttribute('data-tab')) === 'mas', 'desde «Más» se abre Progreso y el menú sigue en «Más»');
  await page.click('#nav [data-tab="mas"]'); await page.click('.mrow[data-act="privacy"]'); await page.waitForSelector('#dlg[open]');
  ok(/Aviso de privacidad/.test(await txt('#dlg')) && /Quién maneja tus datos/.test(await txt('#dlg')), 'el aviso de privacidad se abre desde «Más»');
  await page.keyboard.press('Escape'); await page.waitForTimeout(200);
  await page.click('.mrow[data-act="settings"]'); await page.waitForSelector('#dlg[open]');
  ok(/Ajustes/.test(await txt('#dlg .sheet-h')), 'los ajustes se abren desde «Más»');
  await page.keyboard.press('Escape'); await page.waitForTimeout(200);
  await logout();

  console.log('3. Atleta: Hoy · Semana · Progreso · Máximos · Más');
  await signup('Camila Rojas', 'camila@correo.cl', 'F');
  const auid = await page.evaluate(() => __fake.uid('camila@correo.cl'));
  await page.evaluate(u => __fake.admin('members/' + u, { name: 'Camila Rojas', email: 'camila@correo.cl', approvedAt: Date.now() }), auid);
  await page.waitForSelector('#appRoot:not([hidden])'); await page.waitForTimeout(400);
  ok((await navLabels()).join('|') === 'Hoy|Semana|Progreso|Máximos|Más', 'menú de la atleta: ' + (await navLabels()).join(' · '));
  ok((await css('#nav button[aria-current="page"]', 'color')) === 'rgb(20, 35, 59)', 'pestaña activa en tinta #14233B con ícono dorado');
  await shot('04-hoy-atleta');
  await page.click('#nav [data-tab="mas"]'); await page.waitForTimeout(250);
  mas = await txt('#view');
  ok(/Camila Rojas/.test(mas) && /Femenino/.test(mas) && /Datos en la nube/.test(mas), '«Más»: perfil con sexo y estado de la nube');
  ok(/Plan semanal libre/.test(mas) && /Historial de sesiones/.test(mas) && /Mis ejercicios/.test(mas) && /Calculadora de discos/.test(mas), 'entrenamiento: plan libre, historial, ejercicios y discos');
  ok(!/Descargar respaldo/.test(mas), 'la atleta no ve el respaldo del equipo');
  await shot('05-mas-atleta');
  await page.click('.mrow[data-tab="plan"]'); await page.waitForTimeout(250);
  ok(/Plan/.test(await txt('#view h1')) && (await page.locator('#nav [aria-current="page"]').getAttribute('data-tab')) === 'mas', 'el plan semanal libre se abre desde «Más»');
  await page.click('#nav [data-tab="mas"]'); await page.click('.mrow[data-tab="hist"]'); await page.waitForTimeout(250);
  ok(/Historial/.test(await txt('#view h1')), 'el historial se abre desde «Más»');
  await page.click('[data-act="tab"][data-tab="mas"].lnk'); await page.waitForTimeout(200);
  ok(/Más/.test(await txt('#view h1')), 'y se puede volver');
  await page.click('.mrow[data-act="open-plates"]'); await page.waitForTimeout(250);
  ok(/Qué discos poner/.test(await txt('#view')), 'la calculadora de discos se abre desde «Más»');
  await page.emulateMedia({ colorScheme: 'dark' }); await page.waitForTimeout(200);
  await shot('06-maximos-oscuro');
  await page.click('#nav [data-tab="mas"]'); await page.waitForTimeout(200); await shot('07-mas-oscuro');
  ok((await css('.mlist', 'backgroundColor')) === 'rgb(22, 38, 63)', 'modo oscuro: superficie #16263F');
  await page.emulateMedia({ colorScheme: 'light' });
  await page.click('#nav [data-tab="hoy"]'); await page.waitForTimeout(200);

  ok((await page.evaluate(() => window.__viol)).length === 0, 'sin infracciones de la política de seguridad');
  ok(errors.length === 0, 'sin errores en la consola' + (errors.length ? ': ' + errors.slice(0, 3).join(' | ') : ''));
  await br.close(); srv.close();
  console.log(fails ? '\nFALLAS: ' + fails : '\nTodo bien'); process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
